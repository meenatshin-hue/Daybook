-- Daybook schema: reminders, to-do lists, their items, and settings.
-- Every statement is idempotent, so this file can be run more than once.

create table if not exists public.reminders (
    id        bigint generated by default as identity primary key,
    title     text not null,
    day       date not null,
    "at"      time not null,                       -- local time of day
    label     text not null default '',
    color     text not null default '#1E88E5',
    emoji     text not null default '',
    notified  boolean not null default false,
    created   timestamptz not null default now()
);
create index if not exists reminders_day_idx on public.reminders (day, "at");
create index if not exists reminders_unnotified_idx on public.reminders (id) where not notified;

create table if not exists public.todo_lists (
    id       bigint generated by default as identity primary key,
    name     text not null,
    day      date not null,
    created  timestamptz not null default now()
);
create index if not exists todo_lists_day_idx on public.todo_lists (day);

create table if not exists public.todo_items (
    id       bigint generated by default as identity primary key,
    list_id  bigint not null references public.todo_lists (id) on delete cascade,
    text     text not null,
    done     boolean not null default false,
    created  timestamptz not null default now()
);
create index if not exists todo_items_list_idx on public.todo_items (list_id);

create table if not exists public.settings (
    key    text primary key,
    value  text not null
);

-- The app connects with the secret (service_role) key, which bypasses RLS.
-- With RLS on and no policies, the public anon/publishable key can't read or change anything.
alter table public.reminders  enable row level security;
alter table public.todo_lists enable row level security;
alter table public.todo_items enable row level security;
alter table public.settings   enable row level security;
